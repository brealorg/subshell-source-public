#!/usr/bin/env python3
"""Generate app/src/main/java/app/subshell/prototype/ui/symbols/Symbols.kt.

MATERIALSYMBOLS01 (owner 2026-10-18): the app's icons are Google's Material
Symbols (Rounded, weight 400, grade 0, optical size 24), outlined by default
and filled where a row in symbols.tsv asks for a filled variant (an "on"
state: the selected tab, saved, voted, favourite, playing).

The Android vector drawables come from github.com/google/material-design-icons
(symbols/android/<name>/materialsymbolsrounded/<name>[_fill1]_24px.xml,
Apache License 2.0). Downloads are cached in --cache (outside the repo), so a
rerun with a full cache works offline.

    tools/symbols/generate-symbols.py --cache /tmp/symbols-cache
"""

import argparse
import pathlib
import re
import sys
import urllib.request
import xml.etree.ElementTree as ElementTree

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = ROOT / "tools/symbols/symbols.tsv"
OUTPUT = ROOT / "app/src/main/java/app/subshell/prototype/ui/symbols/Symbols.kt"
# SECAUDIT22_UPSTREAM_IS_PINNED_TO_A_COMMIT_V1: a fixed commit, not the moving
# master branch; it reproduces the Symbols.kt of 2026-10-18 byte for byte.
# Moving it is a reviewed change: regenerate and read the Symbols.kt diff.
UPSTREAM_COMMIT = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
URL = (
    f"https://raw.githubusercontent.com/google/material-design-icons/{UPSTREAM_COMMIT}/"
    "symbols/android/{name}/materialsymbolsrounded/{name}{fill}_24px.xml"
)
ANDROID = "{http://schemas.android.com/apk/res/android}"
PATH_DATA = re.compile(r"[MmLlHhVvCcSsQqTtAaZzEe0-9.,\- ]+")


def read_table():
    rows = []
    for line in TABLE.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        kotlin_name, symbol, mirror, filled = line.split("\t")
        rows.append((kotlin_name, symbol, mirror == "mirror", filled == "filled"))
    return rows


def fetch(cache, symbol, fill):
    target = cache / f"{symbol}{fill}_24px.xml"
    if not target.exists():
        with urllib.request.urlopen(URL.format(name=symbol, fill=fill), timeout=30) as response:
            target.write_bytes(response.read())
    return target.read_text()


def paths_of(source, label):
    vector = ElementTree.fromstring(source)
    if vector.tag != "vector":
        sys.exit(f"{label}: root is {vector.tag}, not vector")
    viewport = vector.get(ANDROID + "viewportWidth")
    if viewport != vector.get(ANDROID + "viewportHeight"):
        sys.exit(f"{label}: the viewport is not square")
    paths = []
    for child in vector:
        if child.tag != "path":
            sys.exit(f"{label}: unexpected <{child.tag}> (groups and transforms are not supported)")
        path = child.get(ANDROID + "pathData")
        # SECAUDIT22_PATH_DATA_IS_ONLY_PATH_COMMANDS_V1: the path goes into a
        # Kotlin string literal, so a quote, backslash or "$" from a tampered
        # download would become code.
        if path is None or not PATH_DATA.fullmatch(path):
            sys.exit(f"{label}: pathData is not plain path commands and numbers")
        paths.append(path)
    if not paths:
        sys.exit(f"{label}: no paths")
    return float(viewport), paths


def kotlin_property(name, drawable, mirror):
    viewport, paths = drawable
    lines = [
        f"    val {name}: ImageVector by lazy {{",
        "        symbol(",
        f'            "{name}",',
        f"            autoMirror = {'true' if mirror else 'false'},",
        f"            viewport = {viewport:g}f,",
    ]
    lines += [f'            "{path}",' for path in paths]
    lines += ["        )", "    }", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", required=True, type=pathlib.Path)
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)

    properties = []
    for kotlin_name, symbol, mirror, filled in read_table():
        properties.append(kotlin_property(kotlin_name, paths_of(fetch(args.cache, symbol, ""), symbol), mirror))
        if filled:
            filled_drawable = paths_of(fetch(args.cache, symbol, "_fill1"), symbol + "_fill1")
            properties.append(kotlin_property(kotlin_name + "Filled", filled_drawable, mirror))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by tools/symbols/generate-symbols.py from tools/symbols/symbols.tsv. Do not edit.\n"
        "// Icons: Google Material Symbols (Rounded, weight 400, grade 0, optical size 24),\n"
        "// github.com/google/material-design-icons, Apache License 2.0.\n"
        "package app.subshell.prototype.ui.symbols\n\n"
        "import androidx.compose.ui.graphics.Color\n"
        "import androidx.compose.ui.graphics.SolidColor\n"
        "import androidx.compose.ui.graphics.vector.ImageVector\n"
        "import androidx.compose.ui.graphics.vector.PathParser\n"
        "import androidx.compose.ui.unit.dp\n\n"
        "/**\n"
        " * MATERIALSYMBOLS01_ICONS_ARE_MATERIAL_SYMBOLS_V1: every icon in the app.\n"
        " * Outlined by default; a `…Filled` variant marks an \"on\" state.\n"
        " */\n"
        "object Symbols {\n"
        + "\n".join(properties)
        + "}\n\n"
        "private fun symbol(name: String, autoMirror: Boolean, viewport: Float, vararg paths: String): ImageVector =\n"
        "    ImageVector.Builder(\n"
        '        name = "Symbols.$name",\n'
        "        defaultWidth = 24.dp,\n"
        "        defaultHeight = 24.dp,\n"
        "        viewportWidth = viewport,\n"
        "        viewportHeight = viewport,\n"
        "        autoMirror = autoMirror,\n"
        "    ).apply {\n"
        "        paths.forEach { path ->\n"
        "            addPath(PathParser().parsePathString(path).toNodes(), fill = SolidColor(Color.Black))\n"
        "        }\n"
        "    }.build()\n"
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
